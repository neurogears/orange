// One-shot sync pulse on request, for aligning orange (camera PTP time) to
// another acquisition system (e.g. Bonsai + Harp) that logs a camera GPO line.
//
// The other PC sends "pulse" over ZeroMQ (REQ -> orange's REP socket). orange
// lets exactly one exposure of the sync camera through to the Harp input and
// replies with that frame's PTP timestamp. Both the edge and its timestamp
// come from the camera itself: the pulse is the camera's own "Exposure"
// output, so it is generated by the sensor timing, and the frame timestamp is
// latched by the camera in PTP time. Nothing is estimated from network round
// trips.
//
// Two GPO lines are used, and neither line's mode changes while the camera
// streams: on the rig's HB cameras a GPO_<N>_Mode write mid-stream is held
// until a fixed point of the frame cycle and restarts the frame in progress,
// which costs two frames (docs/zmq_sync.md). Polarity writes take ~100 us
// and do not disturb capture.
//
// - The exposure line is in "Exposure" mode while streaming: one pulse per
//   exposure.
// - The gate line is in manual "GPO" mode; its polarity is the gate, closed
//   between requests.
// - The Harp input sees exposure AND gate (a logic gate, or both lines on
//   Harp inputs and the AND in Bonsai).
//
// For a pulse, the gate opens in the gap before one exposure and closes in
// the gap after it:
//
//     frame ts:   T0            T1            T2
//     exposure:   _|##|__________|##|__________|##|_
//     gate:       ______|‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾|__________
//     AND:        _______________|‾‾|_______________
//                       ^ open           ^ close
//
// The gaps are where exposures are not, which depends on whether the frame
// timestamp marks the start or the end of the exposure. Configured, the gate
// edges aim at the middle of the gap (margin ±(period - exposure) / 2).
// Unknown, they aim at the half-period mark, the part of the gap common to
// both conventions (margin ±(period / 2 - exposure)). "probe" requests tell
// the two apart on the Harp log (docs/zmq_sync.md).
//
// Each gate edge is bounded in PTP time from the host time around its write
// and a PTP latch right after it; the reply says whether both edges' bounds
// stayed clear of the exposures.
//
// Protocol (one text message each way, REQ/REP):
//   "pulse"               -> one pulse, reply when the pulsed frame has arrived
//   "pulse <id>"          -> same, <id> (any text) is echoed back
//   "probe <us> [<id>]"   -> open the gate <us> after a frame timestamp and
//                            close it one period later (finding the
//                            timestamp convention)
//   "status"              -> state, no pulse
// The reply is one line of JSON; see docs/zmq_sync.md.

// The GVCP a pulse needs from the sync camera. sync_pulse_evt.h wraps the EVT
// SDK; tests substitute a simulated camera. Calls are made with the camera's
// GVCP lock held (SyncPulseConfig::gvcp_mutex).
class SyncPulseCamera {
  public:
    virtual ~SyncPulseCamera() = default;
    // Latch the camera's PTP clock and read it back. *host_ns: steady_clock
    // time (ns) at the midpoint of the latch command's round trip, *rtt_ns
    // that round trip (the latch happened within ±rtt/2 of *host_ns).
    virtual bool LatchPtp(uint64_t *ptp_ns, int64_t *host_ns,
                          int64_t *rtt_ns) = 0;
    virtual bool GetGpoMode(int line, std::string *mode) = 0;
    virtual bool SetGpoMode(int line, const std::string &mode) = 0;
    virtual bool GetGpoPolarity(int line, bool *polarity) = 0;
    virtual bool SetGpoPolarity(int line, bool polarity) = 0;
};

// What moment of the exposure the camera's frame timestamp marks.
enum class SyncTimestampMarks { Unknown, ExposureStart, ExposureEnd };

// "exposure_start" / "exposure_end" / anything else = Unknown.
SyncTimestampMarks parse_sync_timestamp_marks(const std::string &s);
const char *sync_timestamp_marks_name(SyncTimestampMarks m);

struct SyncPulseConfig {
    std::string camera_serial;
    int exposure_gpo = 0;            // in Exposure mode while streaming
    int gate_gpo = 1;                // in GPO mode, polarity = gate
    bool gate_open_polarity = true;  // GPO_<gate>_Polarity that opens it
    SyncTimestampMarks timestamp_marks = SyncTimestampMarks::Unknown;
    double exposure_ns = 0;  // camera exposure
    double period_ns = 0;    // nominal frame period (1e9 / frame rate)
    std::mutex *gvcp_mutex = nullptr; // this camera's GVCP lock
    std::string log_path;    // per-pulse csv; empty = none (not recording)
};

struct SyncPulseResult; // sync_pulse.cpp

class SyncPulse {
  public:
    ~SyncPulse();

    // ZeroMQ REP server, e.g. endpoint "tcp://*:5560". Runs until StopServer.
    bool StartServer(const std::string &endpoint);
    void StopServer();
    bool ServerRunning() const { return server_thread_.joinable(); }
    std::string Endpoint() const { return endpoint_; }

    // Sync camera's capture thread. Attach before AcquisitionStart: stores
    // both lines' modes and the gate's polarity, closes the gate and sets the
    // modes. OnFrame for every frame received. Detach after AcquisitionStop:
    // waits for a pulse in progress and restores the lines. No mode is
    // written in between.
    bool Attach(std::unique_ptr<SyncPulseCamera> camera,
                const SyncPulseConfig &config);
    void OnFrame(uint64_t timestamp_ns, uint64_t frame_id);
    void Detach();

    // Handles one request message and returns the reply (the server calls
    // this; exposed for tests).
    std::string HandleRequest(const std::string &request);

    // For the GUI. PulseCount counts since the last Attach.
    bool Attached() const { return attached_.load(); }
    uint64_t PulseCount() const { return pulses_.load(); }
    std::string LastReply();

  private:
    void ServerLoop(void *socket);
    std::string Pulse(const std::string &id);
    std::string Probe(const std::string &args);
    std::string Status(const std::string &id);
    // Gap between a frame timestamp and the next, as offsets from the
    // earlier timestamp, for the configured convention.
    void GapWindow(double P, double *lo, double *hi) const;
    bool LatestFrame(uint64_t *ts, double *period);
    bool SetGate(uint64_t target_ptp, bool open, uint64_t *earliest,
                 uint64_t *latest);
    void Log(const SyncPulseResult &r);

    // Server.
    std::string endpoint_;
    void *zmq_context_ = nullptr;
    std::thread server_thread_;
    std::atomic<bool> stop_server_{false};

    // Held for a whole pulse (both gate writes) and by Attach/Detach, so the
    // lines are never restored while a pulse is using them.
    std::mutex pulse_mutex_;
    std::unique_ptr<SyncPulseCamera> camera_;
    SyncPulseConfig config_;
    std::string exposure_original_mode_, gate_original_mode_;
    bool gate_original_polarity_ = false;
    std::ofstream log_;
    std::atomic<bool> attached_{false};
    std::atomic<uint64_t> pulses_{0};
    // PTP -> host clock, from the latest latch. Over the ~50 ms a pulse
    // takes, the two clocks' rate difference is far below a microsecond.
    uint64_t map_ptp_ = 0;
    int64_t map_host_ = 0;
    // Latest polarity write's round trip; its midpoint is aimed at the
    // target.
    int64_t write_rtt_ns_ = 100000;

    // Latest frame, from the capture thread.
    std::mutex frame_mutex_;
    std::condition_variable frame_cv_;
    bool have_frame_ = false;
    uint64_t last_ts_ = 0, last_frame_id_ = 0;
    double measured_period_ns_ = 0;
    uint64_t want_ts_ = 0; // pulsed frame being waited for (0 = none)
    bool got_want_ = false, passed_want_ = false;
    uint64_t got_ts_ = 0, got_frame_id_ = 0;

    std::mutex reply_mutex_;
    std::string last_reply_;
};

// The one instance: orange.cpp runs its server, the sync camera's capture
// thread attaches to it.
extern SyncPulse g_sync_pulse;

#endif
